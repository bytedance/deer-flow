def _parse_gateway(value: str) -> tuple[str, str]:
    name, sep, url = value.partition("=")
    if not sep or not name or not url:
        raise argparse.ArgumentTypeError("expected NAME=URL, e.g. A=http://127.0.0.1:8001")
    return name, url.rstrip("/")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    render = sub.add_parser("render-config", help="write the multi-instance config.yaml")
    render.add_argument("--base", required=True, type=Path)
    render.add_argument("--out", required=True, type=Path)
    render.add_argument("--database-url", required=True)
    render.add_argument("--redis-url", required=True)
    render.add_argument("--state-dir", required=True, type=Path)
    render.add_argument("--keep-channels", action="store_true")

    secrets_cmd = sub.add_parser("secrets", help="create the shared secrets file if missing")
    secrets_cmd.add_argument("--out", required=True, type=Path)

    nginx = sub.add_parser("nginx-conf", help="write the round-robin nginx config")
    nginx.add_argument("--out", required=True, type=Path)
    nginx.add_argument("--state-dir", required=True, type=Path)
    nginx.add_argument("--listen-port", required=True, type=int)
    nginx.add_argument("--gateway-port", required=True, type=int, action="append")
    nginx.add_argument("--frontend-port", type=int, default=3000)

    check = sub.add_parser("check", help="run the cross-instance checks")
    check.add_argument("--gateway", required=True, type=_parse_gateway, action="append", help="NAME=URL; pass exactly two")
    check.add_argument("--nginx", default=None)
    check.add_argument("--state-dir", required=True, type=Path)
    check.add_argument("--with-llm", action="store_true", help="allow checks that start a run on a configured model")
    check.add_argument("--timeout", type=float, default=15.0)

    args = parser.parse_args(argv)

    if args.command == "render-config":
        for note in render_config(args.base, args.out, database_url=args.database_url, redis_url=args.redis_url, state_dir=args.state_dir, keep_channels=args.keep_channels):
            print(f"  note: {note}")
        return 0
    if args.command == "secrets":
        ensure_secrets_file(args.out)
        return 0
    if args.command == "nginx-conf":
        _write_private_text(args.out, render_nginx_conf(listen_port=args.listen_port, gateway_ports=args.gateway_port, frontend_port=args.frontend_port, state_dir=args.state_dir))
        return 0
    if args.command == "check":
        if len(args.gateway) != 2:
            parser.error("check needs exactly two --gateway NAME=URL values")
        secrets_path = args.state_dir / "secrets.env"
        token = read_env_file(secrets_path).get("DEER_FLOW_INTERNAL_AUTH_TOKEN", "") if secrets_path.is_file() else ""
        harness = Harness(gateways=args.gateway, nginx_url=(args.nginx or "").rstrip("/") or None, state_dir=args.state_dir, with_llm=args.with_llm, timeout=args.timeout, internal_token=token)
        return exit_code(run_checks(harness))
    return 2


if __name__ == "__main__":
    sys.exit(main())
