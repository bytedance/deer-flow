def generate_shared_secrets() -> dict[str, str]:
    return {
        "AUTH_JWT_SECRET": secrets.token_urlsafe(32),
        "DEER_FLOW_INTERNAL_AUTH_TOKEN": secrets.token_urlsafe(32),
        # A raw urlsafe-base64 32-byte Fernet key, not a passphrase.
        "DEER_FLOW_CREDENTIALS_KEY": base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii"),
        "DEERFLOW_MI_POSTGRES_PASSWORD": secrets.token_hex(16),
    }


def read_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def ensure_secrets_file(path: Path) -> dict[str, str]:
    """Create the shell-sourceable secrets file once (``O_EXCL``, 0600) and return it."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    values = generate_shared_secrets()
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return read_env_file(path)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write("# Shared by every Gateway of the dev_multi_instance harness. Do not commit.\n")
        for name in SHARED_SECRET_NAMES:
            fh.write(f"{name}={values[name]}\n")
    return values


