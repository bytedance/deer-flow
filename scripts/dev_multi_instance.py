PASS, FAIL, SKIP = "PASS", "FAIL", "SKIP"


@dataclass
class CheckResult:
    name: str
    status: str
    detail: str


@dataclass
class SSEEvent:
    id: str | None
    event: str | None
    data: str


def parse_sse_events(lines: Iterable[str]) -> Iterator[SSEEvent]:
    """Yield server-sent events from decoded lines (blank line = dispatch)."""
    event_id: str | None = None
    event_name: str | None = None
    data: list[str] = []
    for raw in lines:
        line = raw.rstrip("\r\n")
        if not line:
            if event_name is not None or data or event_id is not None:
                yield SSEEvent(event_id, event_name, "\n".join(data))
            event_id, event_name, data = None, None, []
            continue
        if line.startswith(":"):
            continue
        name, _, value = line.partition(":")
        value = value[1:] if value.startswith(" ") else value
        if name == "id":
            event_id = value
        elif name == "event":
            event_name = value
        elif name == "data":
            data.append(value)
    if event_name is not None or data or event_id is not None:
        yield SSEEvent(event_id, event_name, "\n".join(data))


def exit_code(results: Iterable[CheckResult]) -> int:
    return 1 if any(result.status == FAIL for result in results) else 0


class CheckFailed(Exception):
    """A check's expectation did not hold; the message is the reported detail."""


class CheckSkipped(Exception):
    """A check cannot run in this setup; the message says why."""


@dataclass
class Harness:
    """State shared by the checks: two Gateways, an optional nginx, one session."""

    gateways: list[tuple[str, str]]
    nginx_url: str | None
    state_dir: Path
    with_llm: bool
    timeout: float
    internal_token: str = ""
    cookies: dict[str, str] = field(default_factory=dict)
    user: dict[str, Any] = field(default_factory=dict)
    is_admin: bool = False
    thread_id: str | None = None
    models: list[Any] | None = None

    def __post_init__(self) -> None:
        import httpx

        # Every target is loopback: never route it through an HTTP(S)_PROXY from the shell.
        self.http = httpx.Client(timeout=httpx.Timeout(self.timeout, read=max(self.timeout, 60.0)), follow_redirects=False, trust_env=False)

    # -- request helpers -----------------------------------------------------

    def headers(self, *, mutating: bool = False) -> dict[str, str]:
        headers: dict[str, str] = {}
        if self.cookies:
            headers["Cookie"] = "; ".join(f"{name}={value}" for name, value in self.cookies.items())
        if mutating and "csrf_token" in self.cookies:
            headers["X-CSRF-Token"] = self.cookies["csrf_token"]
        return headers

    def request(self, method: str, base: str, path: str, *, expect: Iterable[int] = (200,), session: bool = True, **kwargs: Any):
        mutating = method.upper() in {"POST", "PUT", "PATCH", "DELETE"}
        headers = {**(self.headers(mutating=mutating) if session else {}), **kwargs.pop("headers", {})}
        response = self.http.request(method, f"{base}{path}", headers=headers, **kwargs)
        self.http.cookies.clear()  # cookies travel explicitly, never through the jar
        if response.status_code not in tuple(expect):
            raise CheckFailed(f"{method} {base}{path} -> HTTP {response.status_code}: {response.text[:300]}")
        return response

    @property
    def a(self) -> str:
        return self.gateways[0][1]

    @property
    def b(self) -> str:
        return self.gateways[1][1]

    # -- session ---------------------------------------------------------------

    def _adopt_session(self, response) -> None:
        for name in ("access_token", "csrf_token"):
            value = response.cookies.get(name)
            if value:
                self.cookies[name] = value
        self.http.cookies.clear()
        if "access_token" not in self.cookies:
            raise CheckFailed(f"{response.request.url} set no access_token cookie")

    def ensure_session(self) -> str:
        """Log in as the harness's throwaway user, creating it on first use."""
        creds_path = self.state_dir / "check-user.json"
        if creds_path.is_file():
            creds = json.loads(creds_path.read_text(encoding="utf-8"))
            response = self.request("POST", self.a, "/api/v1/auth/login/local", data={"username": creds["email"], "password": creds["password"]}, expect=(200, 401))
            if response.status_code == 200:
                self._adopt_session(response)
                self.is_admin = bool(creds.get("admin"))
                return f"logged in as {creds['email']} on A"
        creds = {"email": f"mi-check-{secrets.token_hex(4)}@example.com", "password": secrets.token_urlsafe(18)}
        setup = self.request("GET", self.a, "/api/v1/auth/setup-status").json()
        if setup.get("needs_setup"):
            response = self.request("POST", self.a, "/api/v1/auth/initialize", json=creds, expect=(201,))
            creds["admin"] = True
        else:
            response = self.request("POST", self.a, "/api/v1/auth/register", json=creds, expect=(201,))
            creds["admin"] = False
        self._adopt_session(response)
        self.is_admin = creds["admin"]
        _write_private_text(creds_path, json.dumps(creds))
        role = "admin" if self.is_admin else "user"
        return f"created throwaway {role} {creds['email']} on A (credentials: {creds_path})"


def _check_health(h: Harness) -> str:
    seen = []
    for name, base in h.gateways:
        body = h.request("GET", base, "/health/ready").json()
        if body.get("status") != "ready" or body.get("stream_bridge") != "ok":
            raise CheckFailed(f"{name} /health/ready: {body}")
        seen.append(f"{name}: database={body.get('database')} stream_bridge={body.get('stream_bridge')}")
    return "; ".join(seen)


def _check_session(h: Harness) -> str:
    created = h.ensure_session()
    me_a = h.request("GET", h.a, "/api/v1/auth/me").json()
    me_b = h.request("GET", h.b, "/api/v1/auth/me").json()
    if me_a.get("id") != me_b.get("id"):
        raise CheckFailed(f"A sees user {me_a.get('id')}, B sees {me_b.get('id')}")
    h.user = me_a
    return f"{created}; B accepts A's session (shared AUTH_JWT_SECRET)"


def _check_internal_token(h: Harness) -> str:
    if not h.internal_token:
        raise CheckSkipped("no DEER_FLOW_INTERNAL_AUTH_TOKEN in the secrets file")
    bodies = []
    for _name, base in h.gateways:
        # Negative control first: without a session, a wrong token must be refused.
        h.request("GET", base, "/api/models", session=False, headers={"X-DeerFlow-Internal-Token": "not-the-token"}, expect=(401,))
        bodies.append(h.request("GET", base, "/api/models", session=False, headers={"X-DeerFlow-Internal-Token": h.internal_token}).json())
    models = bodies[0].get("models", []) if isinstance(bodies[0], dict) else []
    h.models = models
    return f"both Gateways accept the shared DEER_FLOW_INTERNAL_AUTH_TOKEN ({len(models)} model(s) configured)"


def _require_thread(h: Harness) -> str:
    if h.thread_id is None:
        raise CheckSkipped("no thread (thread check did not pass)")
    return h.thread_id


def _check_thread(h: Harness) -> str:
    created = h.request("POST", h.a, "/api/threads", json={"metadata": {"source": "dev_multi_instance check"}}).json()
    thread_id = created["thread_id"]
    fetched = h.request("GET", h.b, f"/api/threads/{thread_id}").json()
    if fetched.get("thread_id") != thread_id:
        raise CheckFailed(f"B returned {fetched}")
    h.thread_id = thread_id
    return f"thread {thread_id} created on A is readable on B"


def _check_upload(h: Harness) -> str:
    thread_id = _require_thread(h)
    name = f"mi-check-{secrets.token_hex(4)}.txt"
    payload = f"multi-instance upload {secrets.token_hex(16)}\n".encode()
    uploaded = h.request("POST", h.a, f"/api/threads/{thread_id}/uploads", files={"files": (name, payload, "text/plain")}).json()
    info = next((item for item in uploaded.get("files", []) if item.get("filename") == name), None)
    if info is None:
        raise CheckFailed(f"A did not report {name}: {uploaded}")
    listed = h.request("GET", h.b, f"/api/threads/{thread_id}/uploads/list").json()
    if name not in {item.get("filename") for item in listed.get("files", [])}:
        raise CheckFailed(f"B does not list {name}: {listed}")
    body = h.request("GET", h.b, info["artifact_url"]).content
    if body != payload:
        raise CheckFailed(f"B served {len(body)} bytes that differ from the {len(payload)} uploaded on A")
    return f"uploaded on A; B lists it and serves identical bytes via {info['artifact_url']}"


def _check_skill_toggle(h: Harness) -> str:
    if not h.is_admin:
        raise CheckSkipped("the check user is not an admin (an admin already existed); PUT /api/skills is admin-only")
    skills = h.request("GET", h.a, "/api/skills").json().get("skills", [])
    skill = next((s for s in skills if s.get("category") == "public"), None)
    if skill is None:
        raise CheckSkipped("no public skill to toggle")
    name, original = skill["name"], bool(skill.get("enabled", True))
    h.request("PUT", h.a, f"/api/skills/{name}", json={"enabled": not original})
    try:
        started = time.monotonic()
        deadline = started + 30
        while True:
            seen = {s["name"]: s.get("enabled") for s in h.request("GET", h.b, "/api/skills").json().get("skills", [])}
            if seen.get(name) is (not original):
                return f"skill {name!r} toggled on A is {'enabled' if not original else 'disabled'} on B after {time.monotonic() - started:.1f}s (restored)"
            if time.monotonic() > deadline:
                raise CheckFailed(f"B still reports {name!r} enabled={seen.get(name)} 30s after A toggled it")
            time.sleep(1)
    finally:
        h.request("PUT", h.a, f"/api/skills/{name}", json={"enabled": original})


def _check_nginx(h: Harness) -> str:
    if not h.nginx_url:
        raise CheckSkipped("nginx is not running (up --no-nginx, or nginx not installed)")
    expected = {base.split("://", 1)[1] for _name, base in h.gateways}
    upstreams = set()
    for _ in range(2 * len(h.gateways) + 2):
        response = h.request("GET", h.nginx_url, "/health")
        upstreams.add(response.headers.get("x-deerflow-upstream", ""))
    if not expected <= upstreams:
        raise CheckFailed(f"nginx reached {sorted(upstreams)}, expected every Gateway {sorted(expected)}")
    detail = f"round-robin reached {', '.join(sorted(expected))}"
    if h.thread_id:
        for _ in range(len(h.gateways) * 2):
            h.request("GET", h.nginx_url, f"/api/threads/{h.thread_id}")
        detail += f"; thread {h.thread_id} readable through every upstream"
    return detail


def bounded_lines(lines: Iterable[str], *, deadline: float, what: str, clock: Callable[[], float] = time.monotonic) -> Iterator[str]:
    """Yield raw SSE lines until *deadline*, counting comment heartbeats too.

    The production stream keeps an idle live run open with ``: heartbeat``
    comments, which the event parser drops and which also reset httpx's read
    timeout, so the budget must be enforced per raw line, not per event.
    """
    for line in lines:
        if clock() > deadline:
            raise CheckFailed(f"{what} exceeded its time budget without reaching `end`")
        yield line


def _read_stream(h: Harness, base: str, path: str, *, last_event_id: str | None = None, budget: float = 90.0) -> list[SSEEvent]:
    headers = {**h.headers(), "Accept": "text/event-stream"}
    if last_event_id:
        headers["Last-Event-ID"] = last_event_id
    events: list[SSEEvent] = []
    deadline = time.monotonic() + budget
    try:
        with h.http.stream("GET", f"{base}{path}", headers=headers) as response:
            if response.status_code != 200:
                response.read()
                raise CheckFailed(f"GET {base}{path} -> HTTP {response.status_code}: {response.text[:300]}")
            for event in parse_sse_events(bounded_lines(response.iter_lines(), deadline=deadline, what=f"GET {base}{path} ({budget:g}s budget)")):
                events.append(event)
                if event.event == "end":
                    break
    finally:
        h.http.cookies.clear()
    return events


def _check_sse_resume(h: Harness) -> str:
    thread_id = _require_thread(h)
    if not h.with_llm:
        # Only a confirmed empty model list makes the run free (it fails before any LLM call).
        if h.models is None:
            raise CheckSkipped("model discovery did not succeed, so a run might call an LLM; rerun with `check --with-llm`")
        if h.models:
            raise CheckSkipped(f"{len(h.models)} model(s) configured: a run would call the LLM; rerun with `check --with-llm`")
    body = {"assistant_id": "lead_agent", "input": {"messages": [{"role": "user", "content": "Reply with the single word: pong"}]}}
    run = h.request("POST", h.a, f"/api/threads/{thread_id}/runs", json=body).json()
    run_id = run["run_id"]
    path = f"/api/threads/{thread_id}/runs/{run_id}/join"
    full = _read_stream(h, h.b, path)
    ids = [event.id for event in full if event.id]
    if not full or full[-1].event != "end":
        raise CheckFailed(f"joining on B did not reach `end`: {[e.event for e in full]}")
    if len(ids) < 2:
        raise CheckSkipped(f"run {run_id} produced only {len(ids)} event id(s); nothing to resume from")
    resumed = _read_stream(h, h.a, path, last_event_id=ids[0])
    resumed_ids = [event.id for event in resumed if event.id]
    if resumed_ids != ids[1:]:
        raise CheckFailed(f"resuming on A after {ids[0]} returned ids {resumed_ids}, expected {ids[1:]}")
    status = h.request("GET", h.b, f"/api/threads/{thread_id}/runs/{run_id}").json().get("status")
    kind = "no-model (fails fast, no LLM call)" if h.models == [] else "LLM"
    return f"{kind} run {run_id} created on A (status {status}); B replayed {len(full)} events; A resumed from Last-Event-ID {ids[0]} with the remaining {len(resumed_ids)}"


CHECKS: list[tuple[str, Callable[[Harness], str]]] = [
    ("health/ready on both (stream_bridge ok)", _check_health),
    ("session from A accepted by B", _check_session),
    ("shared internal auth token", _check_internal_token),
    ("thread created on A visible on B", _check_thread),
    ("upload on A, list + download on B", _check_upload),
    ("skill toggle on A seen by B", _check_skill_toggle),
    ("nginx balances both Gateways", _check_nginx),
    ("SSE join on B, Last-Event-ID resume on A", _check_sse_resume),
]

MANUAL_CHECKS = (
    "`stop b --kill` while A has an active run: A's run must not turn `error`",
    "cancel a run on B from A: takes effect within about one heartbeat (~10s)",
    "change an MCP filesystem server's args on A: B's local-bash allowlist follows",
    "edit a skill on A: B's system-prompt skills section changes within 30s",
    "IM channel gates (one leader per platform, failover, runtime-config): once channel leader election lands",
)


def run_checks(h: Harness, *, out=sys.stdout) -> list[CheckResult]:
    results: list[CheckResult] = []
    for name, check in CHECKS:
        try:
            result = CheckResult(name, PASS, check(h))
        except CheckSkipped as exc:
            result = CheckResult(name, SKIP, str(exc))
        except CheckFailed as exc:
            result = CheckResult(name, FAIL, str(exc))
        except Exception as exc:  # connection errors, unexpected payloads
            result = CheckResult(name, FAIL, f"{type(exc).__name__}: {exc}")
        results.append(result)
        print(f"[{result.status}] {result.name}: {result.detail}", file=out, flush=True)
    counts = {status: sum(1 for r in results if r.status == status) for status in (PASS, FAIL, SKIP)}
    print(f"\n{counts[PASS]} passed, {counts[FAIL]} failed, {counts[SKIP]} skipped", file=out)
    print('Still manual (backend/docs/CONFIGURATION.md, "Local two-Gateway harness"):', file=out)
    for item in MANUAL_CHECKS:
        print(f"  - {item}", file=out)
    return results


